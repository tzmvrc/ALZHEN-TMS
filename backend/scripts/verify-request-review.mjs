import assert from 'node:assert/strict';
import {validateRequestDraft,editableRequestFields} from '../../frontend/src/services/request-draft.ts';
import {homeDemoRequest} from '../../frontend/src/pages/Admin/data/homeDemoRequest.ts';
import {fieldMilestones,submissionAssignment} from '../src/services/field-milestones.logic.ts';
const valid=structuredClone(homeDemoRequest);
assert.deepEqual(validateRequestDraft(valid),[]);
assert(validateRequestDraft({...valid,warehouse:''}).some(error=>error.includes('Warehouse')));
assert(validateRequestDraft({...valid,items:[]}).some(error=>error.includes('cargo')));
assert(validateRequestDraft({...valid,items:[{...valid.items[0],qty:0,totalCbm:NaN}]}).length>=2);
assert(validateRequestDraft({...valid,dispatchDate:'invalid'}).some(error=>error.includes('loading')));
assert(validateRequestDraft({...valid,dispatchDate:'2026-10-24',deliveryDate:'2026-10-23'}).some(error=>error.includes('after loading')));
const patch=editableRequestFields({...valid,status:'Approved',fromEmail:'tampered@example.invalid'});
assert(!Object.hasOwn(patch,'status'));
assert(!Object.hasOwn(patch,'fromEmail'));
assert(!Object.hasOwn(patch,'messageThread'));
patch.items[0].qty=999;
assert.notEqual(valid.items[0].qty,999,'Draft saves must not mutate original extracted email data');
const time='2026-10-24T05:00:00Z';
assert.deepEqual(fieldMilestones('loading_reports',[{id:'load',trip_id:'trip',loading_start_at:time,loading_finished_at:null}]).map(row=>row.event_type),['LOADING_STARTED']);
assert.equal(fieldMilestones('offloads',[{id:'offload',trip_id:'trip',trip_stop_id:'stop',reported_at:time,created_at:'2026-10-23T00:00:00Z'}])[0].event_time,time);
assert.equal(fieldMilestones('trip_stops',[{id:'stop',trip_id:'trip',arrival_time:time}])[0].trip_stop_id,'stop');
assert.deepEqual(fieldMilestones('incidents',[{id:'incident',trip_id:'trip',created_at:'invalid'}]),[]);
assert.deepEqual(fieldMilestones('unknown',[{id:'x',trip_id:'trip',created_at:time}]),[]);
const submission={trip_id:'trip',driver_id:'driver',updated_at:time};
const old={id:'old-truck',trip_id:'trip',driver_id:'driver',assigned_at:'2026-10-22T00:00:00Z',unassigned_at:'2026-10-24T04:00:00Z'};
const current={...old,id:'current-truck',assigned_at:'2026-10-24T04:00:00Z',unassigned_at:null};
assert.equal(submissionAssignment(submission,[old,current]),'current-truck');
assert.equal(submissionAssignment({...submission,updated_at:'2026-10-23T05:00:00Z'},[old,current]),'old-truck');
assert.equal(submissionAssignment(submission,[current,{...current,id:'ambiguous'}]),null);
assert.equal(submissionAssignment(submission,[]),null);
console.log('Request review checks passed: validation, protected fields, immutable originals, and saved operational timestamps.');
